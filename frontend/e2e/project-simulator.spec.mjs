import{test,expect}from'@playwright/test';
test('escenario de término: producción, equipo, costo manual y calendario diario independientes de datos reales',async({page})=>{
  await page.goto('/e2e/fixtures/project-simulator.html');
  await page.getByRole('spinbutton',{name:'Rendimiento Pilas',exact:true}).fill('10');
  await expect(page.getByRole('group',{name:'Término simulado',exact:true})).toContainText('2026-10-26');
  await page.getByRole('button',{name:'2. Costos y equipos'}).click();
  await page.getByRole('checkbox',{name:/Excavadora · EXC-01/}).check();
  await page.getByRole('button',{name:'+ Agregar costo manual',exact:true}).click();
  await page.getByRole('textbox',{name:/Concepto sim-2/}).fill('Arriendo futuro');
  await page.getByRole('spinbutton',{name:'Tarifa Arriendo futuro',exact:true}).fill('100');
  await page.getByRole('combobox',{name:'Cobro Arriendo futuro',exact:true}).selectOption('calendar');
  await expect(page.getByRole('group',{name:'Costo futuro seleccionado',exact:true})).toContainText('$1.200');
  await page.getByRole('button',{name:'3. Calendario diario'}).click();
  await page.getByRole('spinbutton',{name:'Rendimiento manual 2026-10-20',exact:true}).fill('50');
  await expect(page.getByRole('group',{name:'Término simulado',exact:true})).toContainText('2026-10-20');
  await expect(page.getByRole('group',{name:'Costo futuro seleccionado',exact:true})).toContainText('$200');
  await page.getByRole('checkbox',{name:'Trabajar 2026-10-20',exact:true}).uncheck();
  await expect(page.getByRole('group',{name:'Término simulado',exact:true})).toContainText('2026-10-27');
  expect(await page.evaluate(()=>window.props.productionParts[0].quantity)).toBe(60);
  await page.getByRole('button',{name:'1. Rendimientos'}).click();
  await page.getByRole('spinbutton',{name:'Rendimiento Pilas',exact:true}).fill('0');
  await expect(page.getByText('No termina en este horizonte',{exact:true})).toBeVisible();
});
test('trabajador único con promedio diario editable, historial desplegable y selección estable',async({page})=>{
  await page.goto('/e2e/fixtures/project-simulator.html?labor');
  await page.getByRole('button',{name:'2. Costos y equipos'}).click();
  const name='FRANCO REINALDO ERICES ORELLANA';
  const worker=page.getByRole('checkbox',{name:`Seleccionar ${name} · Ficha 123`,exact:true});
  await expect(worker).toHaveCount(1);
  await page.getByText('Ver detalle histórico (6 cargos)',{exact:true}).click();
  await expect(page.getByRole('cell',{name:'2026-10-09',exact:true})).toBeVisible();
  await expect(worker).not.toBeChecked();
  await worker.check();await expect(page.getByRole('spinbutton',{name:`Tarifa ${name}`,exact:true})).toHaveValue('60066');
  await expect(page.getByRole('combobox',{name:`Cobro ${name}`,exact:true})).toHaveValue('workday');
  await page.getByRole('spinbutton',{name:`Tarifa ${name}`,exact:true}).fill('55000');
  await page.evaluate(()=>window.reorderSimulationCatalog());await expect(worker).toBeChecked();
  await expect(page.getByRole('spinbutton',{name:`Tarifa ${name}`,exact:true})).toHaveValue('55000');
  await worker.uncheck();await expect(page.getByRole('spinbutton',{name:`Tarifa ${name}`,exact:true})).toHaveCount(0);
});
