import {test,expect} from '@playwright/test';
test('monthly cost calendar shows daily charges and responds to scenario edits',async({page},testInfo)=>{
 await page.goto('/e2e/fixtures/project-simulator.html');
 await page.getByRole('spinbutton',{name:'Rendimiento Pilas',exact:true}).fill('10');
 await page.getByRole('button',{name:'2. Costos y equipos'}).click();
 await page.getByRole('checkbox',{name:/Excavadora · EXC-01/}).check();
 await page.getByRole('button',{name:'+ Agregar costo manual',exact:true}).click();
 await page.getByRole('textbox',{name:'Concepto sim-2'}).fill('Arriendo calendario');
 await page.getByRole('spinbutton',{name:'Tarifa Arriendo calendario',exact:true}).fill('50');
 await page.getByRole('combobox',{name:'Cobro Arriendo calendario',exact:true}).selectOption('calendar');
 const calendar=page.getByRole('region',{name:'Calendario de costos del simulador'});
 await expect(calendar.getByRole('button',{name:/^Costos 2026-10-/})).toHaveCount(31);
 await expect(calendar.getByRole('button',{name:/^Costos 2026-10-01:/})).toBeDisabled();
 await calendar.getByRole('button',{name:/^Costos 2026-10-20:/}).click();
 const detail=calendar.getByRole('region',{name:'Resumen de costos del día'});
 await expect(detail).toContainText('Excavadora · EXC-01');
 await expect(detail).toContainText('Arriendo calendario');
 await expect(detail.getByRole('heading')).toContainText('$150');
 await calendar.getByRole('button',{name:/^Costos 2026-10-24:/}).click();
 await expect(detail).not.toContainText('Excavadora · EXC-01');
 await expect(detail.getByRole('heading')).toContainText('$50');
 await calendar.getByRole('button',{name:/^Costos 2026-10-27:/}).click();
 await expect(detail).toContainText('Sin cargos considerados');
 await calendar.getByLabel('Escenario del calendario').selectOption('Menor rendimiento');
 await expect(detail).toContainText('Excavadora · EXC-01');
 await calendar.getByRole('button',{name:'Mes siguiente de costos'}).click();
 await expect(calendar.getByRole('button',{name:/^Costos 2026-11-/})).toHaveCount(30);
 await calendar.getByRole('button',{name:'Mes anterior de costos'}).click();
 await calendar.getByLabel('Escenario del calendario').selectOption('Escenario base');
 await calendar.getByRole('button',{name:/^Costos 2026-10-20:/}).click();
 await page.getByRole('spinbutton',{name:'Tarifa Arriendo calendario',exact:true}).fill('80');
 await expect(detail.getByRole('heading')).toContainText('$180');
 await calendar.scrollIntoViewIfNeeded();
 await calendar.screenshot({path:testInfo.outputPath('cost-calendar.png')});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
});
