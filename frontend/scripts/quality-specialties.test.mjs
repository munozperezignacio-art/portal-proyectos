import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {PGlite} from '@electric-sql/pglite';
test('specialties isolate works, parts, formats, permissions and immutable protocols',async()=>{
 const db=new PGlite();
 try{
 await db.exec(`create schema private;create schema auth;create role anon;create role authenticated;
 create function auth.uid() returns uuid language sql as $$select nullif(current_setting('test.uid',true),'')::uuid$$;
 create table obras(id integer primary key,empresa text,nombre text);
 create table usuarios(auth_user_id uuid,empresa text,nombre text,usuario text);
 create table partidas_obra(id integer primary key,obra_id integer,empresa text,partida text,es_titulo boolean);
 create function private.rrhh_partidas_permiso(text,integer,text) returns boolean language sql as $$select $2=1$$;
 create function private.obraxis_permission(text,text) returns boolean language sql as $$select $2<>coalesce(current_setting('test.denied',true),'')$$;
 insert into obras values(1,'A','Obra A'),(2,'B','Obra B');
 insert into partidas_obra values(1,1,'A','Hormigón',false),(2,1,'A','Excavación',false),(3,2,'B','Otra',false);
 insert into usuarios values('00000000-0000-4000-8000-000000000001','A','Tester','t');
 set test.uid='00000000-0000-4000-8000-000000000001';`);
 await db.exec(await readFile(new URL('../../supabase/schema/quality-specialties.sql',import.meta.url),'utf8'));
 const call=async(action,data={},work=1)=>(await db.query('select public.quality_specialties_api($1,$2,$3) r',[work,action,JSON.stringify(data)])).rows[0].r;
 await assert.rejects(call('state',{},2),/Sin acceso/);
 await assert.rejects(call('specialty',{nombre:'Otra',part_ids:[3]}),/Partida ajena/);
 await db.exec("set test.denied='obras.especialidad.configurar'");
 await assert.rejects(call('specialty',{nombre:'Hormigón',part_ids:[1]}),/Falta el permiso/);
 await db.exec("set test.denied=''");
 const s=await call('specialty',{nombre:'Hormigón',part_ids:[1,2]});
 const s2=await call('specialty',{nombre:'Movimiento de tierras',part_ids:[2]});
 const t=await call('type',{especialidad_id:s.id,nombre:'Recepción',controles:['Dimensiones','Terminación']});
 const t2=await call('type',{especialidad_id:s2.id,nombre:'Excavación',controles:['Nivel']});
 const payload={id:'10000000-0000-4000-8000-000000000001',especialidad_id:s.id,partida_id:1,tipo_id:t.id,tipo_revision:1,fecha:'2026-11-27',estado:'borrador',resultados:[{resultado:'Conforme'},{resultado:'Pendiente'}]};
 await assert.rejects(call('protocol',{...payload,tipo_id:t2.id}),/incorrecto/);
 await db.exec("set test.denied='obras.calidad.crear'");
 await assert.rejects(call('protocol',payload),/Falta permiso/);
 await db.exec("set test.denied=''");
 assert.equal((await call('protocol',payload)).correlativo,1);
 const snapshot=(await call('state')).protocols[0].snapshot;
 await call('type',{id:t.id,revision:1,especialidad_id:s.id,nombre:'Recepción nueva',controles:['Otro control']});
 assert.deepEqual((await call('state')).protocols[0].snapshot,snapshot);
 await assert.rejects(call('protocol',{...payload,id:'10000000-0000-4000-8000-000000000002'}),/formato cambió/);
 await assert.rejects(call('protocol',{...payload,revision:1,estado:'aprobado'}),/Resuelve/);
 await assert.rejects(call('specialty',{id:s.id,revision:1,nombre:'Hormigón',part_ids:[2]}),/desvincular/);
 await call('protocol',{...payload,revision:1,estado:'aprobado',resultados:[{resultado:'Conforme'},{resultado:'No aplica'}]});
 await assert.rejects(call('protocol',{...payload,revision:2}),/aprobado/);
 await assert.rejects(call('protocol',{...payload,revision:2,especialidad_id:s2.id}),/ajeno/);
 const second={...payload,id:'10000000-0000-4000-8000-000000000002',partida_id:2,tipo_revision:2,resultados:[{resultado:'Conforme'}]};
 assert.equal((await call('protocol',second)).correlativo,1,'Each partida has its own numbering');
 await assert.rejects(call('protocol',second),/modificado/,'Retry cannot duplicate a saved protocol');
 await db.exec("set test.uid=''");await assert.rejects(call('state'),/Sin acceso/);
 }finally{await db.close();}
});
