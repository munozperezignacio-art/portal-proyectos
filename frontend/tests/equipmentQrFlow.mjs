import { chromium } from '@playwright/test';
import { createServer } from 'vite';
import assert from 'node:assert/strict';
const server=await createServer({server:{host:'127.0.0.1',port:5197,strictPort:false}});
await server.listen();
const browser=await chromium.launch({channel:'chrome',headless:true});
try {
 const page=await browser.newPage({viewport:{width:390,height:844}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const calls=[];
 await page.route('**/functions/v1/**',async route=>{
  const body=route.request().postDataJSON();calls.push(body);
  let result={};
  if(route.request().url().endsWith('equipment-documents'))result={documents:[]};
  else if(body.action==='cargar')result={equipo:{empresa:'EMINSG',tipo:'EXCAVADORA',patente:'QA-LOCAL',horometro_inicial:100,unidad:'h'}};
  else if(body.action==='identificar')result={nombre:'Persona de prueba local',cargo:'Operador',rut:body.rut};
  else if(body.action==='mantencion'||body.action==='registrar')result={ok:true,id:123};
  else if(body.action==='checklist')result={formToken:'local-checklist'};
  await route.fulfill({json:result});
 });
 await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/?maquinaria_token=`+'a'.repeat(48));
 await page.getByLabel('Tu RUT').waitFor();
 assert.equal(await page.getByRole('button',{name:'Enviar reporte',exact:true}).count(),0);
 await page.getByLabel('Tu RUT').fill('12.345.678-4');await page.getByRole('button',{name:'Continuar',exact:true}).click();
 await page.getByText('Revisa el RUT y su dígito verificador.').waitFor();
 assert.equal(calls.filter(c=>c.action==='identificar').length,0);
 await page.getByLabel('Tu RUT').fill('12.345.678-5');await page.getByRole('button',{name:'Continuar',exact:true}).click();
 for(const name of ['Documentos','Realizar reporte','Realizar checklist','Registrar mantenimiento'])await page.getByRole('button',{name,exact:true}).waitFor();
 assert.equal(await page.getByRole('button',{name:'Enviar reporte',exact:true}).count(),0);
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await page.screenshot({path:'tests/equipment-qr-menu-local.png',fullPage:true});
 await page.getByRole('button',{name:'Documentos',exact:true}).click();await page.getByText('No hay documentos publicados para este equipo.').waitFor();
 await page.getByRole('button',{name:'Volver al equipo',exact:true}).click();
 await page.getByRole('button',{name:'Registrar mantenimiento',exact:true}).click();
 await page.getByLabel('Trabajo realizado').fill('Prueba local de mantenimiento');
 await page.getByRole('button',{name:'Guardar mantenimiento',exact:true}).click();
 await page.getByText('Mantenimiento #123 guardado en el historial del equipo.').waitFor();
 assert.equal(calls.find(c=>c.action==='mantencion').rut,'123456785');
 await page.getByRole('button',{name:'Volver al equipo',exact:true}).click();
 await page.getByRole('button',{name:'Realizar reporte',exact:true}).click();
 await page.getByLabel('Lectura final (h)').fill('101');
 await page.getByLabel('¿Hubo carga de combustible?').selectOption('no');
 await page.getByLabel('¿Hubo alguna falla?').selectOption('no');
 await page.getByRole('button',{name:'Enviar reporte',exact:true}).click();
 await page.getByText('Reporte #123 recibido').waitFor();
 assert.equal(calls.find(c=>c.action==='registrar').rut,'123456785');
 assert.deepEqual(errors,[]);
 console.log('OK: mobile RUT gate, invalid RUT rejection, four menu actions, documents, report and maintenance payloads. HTTP services mocked; no production records created.');
} finally {await browser.close();await server.close();}
