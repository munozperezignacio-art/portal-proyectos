 await page.getByRole('button',{name:'Editar Nuevo campo (textarea)',exact:true}).waitFor();
 await page.getByRole('button',{name:'Editar Nombre',exact:true}).click();
 await page.locator('.designer-properties input[type=text]').first().fill('Operador');
 await page.getByRole('button',{name:'Editar Operador',exact:true}).waitFor();
 await page.getByText('Campo #1 · Texto corto',{exact:true}).waitFor();
 await page.getByRole('button',{name:'Editar matriz',exact:true}).click();
 await page.getByLabel('Pregunta 1',{exact:true}).fill('Estado de cables');
 await page.getByRole('button',{name:'Aplicar a la matriz'}).click();
 await page.getByRole('button',{name:'Vista previa',exact:true}).click();
 await page.getByRole('button',{name:'Móvil',exact:true}).click();
 assert.equal(await page.locator('.designer-properties').count(),0);
 assert.equal(await page.evaluate(()=>window.designerWrites.length),0);
 await page.getByRole('button',{name:'Diseño',exact:true}).click();
 await page.getByLabel('Buscar elementos').fill('Texto corto');
