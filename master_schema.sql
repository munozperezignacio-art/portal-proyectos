CREATE TABLE IF NOT EXISTS acreditaciones_subcontratos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_nombre TEXT NOT NULL,
    rut_empresa TEXT NOT NULL,
    obra_asociada TEXT,
