-- 1. CONFIGURACIÓN Y EMPRESA
CREATE TABLE IF NOT EXISTS config_empresa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa TEXT NOT NULL,
    logo_base64 TEXT,
    modulos_activos TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);

CREATE TABLE IF NOT EXISTS config_correos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa TEXT NOT NULL,
    modulo TEXT NOT NULL,
    emails TEXT[],
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);

CREATE TABLE IF NOT EXISTS usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL,
    email TEXT UNIQUE NOT NULL,
    rol TEXT NOT NULL DEFAULT 'Inspector',
    empresa TEXT NOT NULL,
    modulos TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);

CREATE TABLE IF NOT EXISTS roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL,
    permisos TEXT,
    empresa TEXT NOT NULL
);

-- 2. OBRAS Y PERSONAL
CREATE TABLE IF NOT EXISTS obras (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT UNIQUE NOT NULL,
    ubicacion TEXT,
    empresa TEXT NOT NULL,
    estado TEXT DEFAULT 'Activa',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);

CREATE TABLE IF NOT EXISTS maestro_personal (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL,
    rut TEXT NOT NULL,
    cargo TEXT,
    obra_nombre TEXT,
    fecha_asig TEXT,
    empresa TEXT NOT NULL,
    estado TEXT DEFAULT 'Activo',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);

CREATE TABLE IF NOT EXISTS inventario_maquinaria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patente TEXT NOT NULL,
    tipo TEXT NOT NULL,
    marca TEXT,
    obra_nombre TEXT,
    empresa TEXT NOT NULL,
    estado TEXT DEFAULT 'Operativo',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);

-- 3. ACREDITACIONES
