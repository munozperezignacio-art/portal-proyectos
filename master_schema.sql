    equipo_docs JSONB,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);

CREATE TABLE IF NOT EXISTS acreditaciones_internas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL,
    rut TEXT NOT NULL,
    obra_asociada TEXT,
    documentos JSONB,
    estado TEXT DEFAULT 'Pendiente',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);

-- 4. FORMULARIOS Y PREVENCIÓN
CREATE TABLE IF NOT EXISTS prevencion_formularios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo TEXT NOT NULL,
    descripcion TEXT,
    modulo_asignado TEXT DEFAULT 'general',
    campos JSONB,
    token_publico TEXT UNIQUE,
    creador_email TEXT,
    empresa TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);

CREATE TABLE IF NOT EXISTS prevencion_respuestas_formularios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    formulario_id BIGINT,
    formulario_titulo TEXT,
    usuario_nombre TEXT,
    usuario_rut TEXT,
    respuestas JSONB,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);

CREATE TABLE IF NOT EXISTS prevencion_capacitaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo TEXT NOT NULL,
    descripcion TEXT,
    tipo TEXT DEFAULT 'Charla 5 Minutos',
    modulo_asignado TEXT DEFAULT 'general',
