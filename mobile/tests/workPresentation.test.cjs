const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const source = fs.readFileSync(path.join(__dirname, '../src/lib/workPresentation.ts'), 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const loaded = { exports: {} };
new Function('exports', 'module', compiled)(loaded.exports, loaded);
const { workStatus, workDescription } = loaded.exports;
assert.deepEqual(workStatus({ estado: null }), { label: 'Activa', tone: 'green' });
assert.deepEqual(workStatus({ estado: ' ' }), { label: 'Activa', tone: 'green' });
assert.deepEqual(workStatus({ estado: ' ACTIVA ' }), { label: 'Activa', tone: 'green' });
assert.deepEqual(workStatus({ estado: 'En pausa' }), { label: 'En pausa', tone: 'amber' });
assert.deepEqual(workStatus({ estado: 'Terminada' }), { label: 'Terminada', tone: 'blue' });
assert.deepEqual(workStatus({ estado: 'Archivada' }), { label: 'Archivada', tone: 'blue' });
assert.deepEqual(workStatus({ estado: 'Inactiva' }), { label: 'Inactiva', tone: 'amber' });
assert.equal(workDescription({ tipo: 'Cimentaciones', cliente: 'EBCO S.A.' }), 'Cimentaciones \u00b7 EBCO S.A.');
assert.equal(workDescription({ area: 'Terreno', cliente: ' ' }), 'Terreno');
assert.equal(workDescription({}), 'Obra');
console.log('Passed work cards: web-compatible default status, explicit states, inactive badge, and clean separator.');
