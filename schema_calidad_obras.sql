CREATE POLICY "Allow_All_Operations_Anon_Authenticated" ON calidad_pac FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);
DROP POLICY IF EXISTS "Allow_All_Operations_Anon_Authenticated" ON calidad_rdi;
CREATE POLICY "Allow_All_Operations_Anon_Authenticated" ON calidad_rdi FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);
DROP POLICY IF EXISTS "Allow_All_Operations_Anon_Authenticated" ON calidad_no_conformidades;
CREATE POLICY "Allow_All_Operations_Anon_Authenticated" ON calidad_no_conformidades FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);
DROP POLICY IF EXISTS "Allow_All_Operations_Anon_Authenticated" ON calidad_recepciones_partidas;
CREATE POLICY "Allow_All_Operations_Anon_Authenticated" ON calidad_recepciones_partidas FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

GRANT ALL ON calidad_pac, calidad_rdi, calidad_no_conformidades, calidad_recepciones_partidas TO anon, authenticated;
