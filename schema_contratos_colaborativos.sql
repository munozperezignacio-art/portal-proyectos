grant select, insert, update on public.contratos_colaborativos to authenticated;
grant select, insert, update on public.contratos_colaborativos_partidas to authenticated;
grant select, insert on public.contratos_colaborativos_eventos to authenticated;
grant usage, select on sequence public.contratos_colaborativos_eventos_id_seq to authenticated;

drop policy if exists "miembros ven contratos colaborativos" on public.contratos_colaborativos;
create policy "miembros ven contratos colaborativos" on public.contratos_colaborativos for select to authenticated
using (private.obraxis_actor_can_access_company(empresa_contratista) or private.obraxis_actor_can_access_company(empresa_colaboradora));

drop policy if exists "contratista crea contratos colaborativos" on public.contratos_colaborativos;
create policy "contratista crea contratos colaborativos" on public.contratos_colaborativos for insert to authenticated
with check (private.obraxis_actor_can_access_company(empresa_contratista));

drop policy if exists "miembros actualizan contratos colaborativos" on public.contratos_colaborativos;
create policy "miembros actualizan contratos colaborativos" on public.contratos_colaborativos for update to authenticated
using (private.obraxis_actor_can_access_company(empresa_contratista) or private.obraxis_actor_can_access_company(empresa_colaboradora))
with check (private.obraxis_actor_can_access_company(empresa_contratista) or private.obraxis_actor_can_access_company(empresa_colaboradora));

