-- Contratos colaborativos entre dos empresas Obraxis.
-- Cada empresa conserva su obra, presupuesto y análisis; solo se comparte el alcance enlazado.

create extension if not exists pgcrypto;

create table if not exists public.contratos_colaborativos (
  id uuid primary key default gen_random_uuid(),
  colaboracion_id bigint not null references public.colaboraciones_obra(id) on delete cascade,
  codigo text not null,
  nombre text not null,
  empresa_contratista text not null,
  rut_contratista text,
  obra_contratista_id integer not null references public.obras(id),
  obra_contratista_nombre text not null,
  empresa_colaboradora text not null,
  rut_colaboradora text,
  obra_colaboradora_id integer references public.obras(id),
  obra_colaboradora_nombre text,
  especialidad text,
  monto_contrato numeric(18,2) not null default 0 check (monto_contrato >= 0),
  fecha_inicio date,
  fecha_termino date,
  estado text not null default 'Configuracion' check (estado in ('Configuracion','Pendiente contraparte','Activo','Suspendido','Terminado','Rechazado')),
  permisos_compartidos jsonb not null default '{"avances":true,"asistencia":true,"estados_pago":true,"calidad":false,"prevencion":false,"libro_obra":false}'::jsonb,
  creado_por text,
  aceptado_por text,
  aceptado_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (colaboracion_id, codigo)
);

create index if not exists contratos_colaborativos_empresas_idx
  on public.contratos_colaborativos (empresa_contratista, empresa_colaboradora, estado);
create index if not exists contratos_colaborativos_obras_idx
  on public.contratos_colaborativos (obra_contratista_id, obra_colaboradora_id);

create table if not exists public.contratos_colaborativos_partidas (
  id uuid primary key default gen_random_uuid(),
  contrato_id uuid not null references public.contratos_colaborativos(id) on delete cascade,
  partida_contratista_id integer not null references public.partidas_obra(id),
  partida_colaboradora_id integer references public.partidas_obra(id),
  codigo_contratista text,
  nombre_contratista text not null,
  codigo_colaboradora text,
  nombre_colaboradora text,
  unidad_contratista text,
  unidad_colaboradora text,
  cantidad_contratada numeric(18,4) not null default 0 check (cantidad_contratada >= 0),
  factor_conversion numeric(18,6) not null default 1 check (factor_conversion > 0),
  ponderacion numeric(9,6) not null default 0 check (ponderacion >= 0),
  estado text not null default 'Pendiente' check (estado in ('Pendiente','Propuesto','Aceptado','Observado','Inactivo')),
  observacion text,
  creado_por text,
  aceptado_por text,
  aceptado_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (contrato_id, partida_contratista_id, partida_colaboradora_id)
);

create index if not exists contratos_colaborativos_partidas_contrato_idx
  on public.contratos_colaborativos_partidas (contrato_id, estado);

create table if not exists public.contratos_colaborativos_eventos (
  id bigint generated by default as identity primary key,
  contrato_id uuid not null references public.contratos_colaborativos(id) on delete cascade,
  empresa text not null,
  accion text not null,
  estado_resultante text,
  detalle text,
  actor_nombre text,
  actor_auth_id uuid default auth.uid(),
  created_at timestamptz not null default now()
);

alter table public.subcontrato_avances add column if not exists contrato_colaborativo_id uuid references public.contratos_colaborativos(id);
