CREATE POLICY maquinaria_fallas_authenticated_select ON public.maquinaria_fallas FOR SELECT TO authenticated
USING (EXISTS (SELECT 1 FROM public.usuarios u WHERE u.auth_user_id = auth.uid() AND (u.empresa = maquinaria_fallas.empresa OR lower(u.empresa) = 'obraxis')));
