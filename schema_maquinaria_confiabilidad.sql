CREATE TABLE IF NOT EXISTS public.maquinaria_fallas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  equipo_id BIGINT NOT NULL REFERENCES public.inventario_maquinaria(id) ON DELETE CASCADE,
  equipo_patente TEXT,
  equipo_tipo TEXT,
  fecha DATE NOT NULL,
  severidad TEXT NOT NULL DEFAULT 'Media' CHECK (severidad IN ('Baja','Media','Alta','Crítica')),
  detuvo_equipo BOOLEAN NOT NULL DEFAULT true,
  horas_fuera_servicio NUMERIC NOT NULL DEFAULT 0 CHECK (horas_fuera_servicio >= 0),
  descripcion TEXT NOT NULL,
  causa TEXT,
  solucion TEXT,
  responsable TEXT,
  registrado_por TEXT,
  empresa TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.maquinaria_mantenciones (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  equipo_id BIGINT NOT NULL REFERENCES public.inventario_maquinaria(id) ON DELETE CASCADE,
  equipo_patente TEXT,
  equipo_tipo TEXT,
  fecha DATE NOT NULL,
  tipo TEXT NOT NULL DEFAULT 'Preventiva' CHECK (tipo IN ('Preventiva','Correctiva','Predictiva','Inspección')),
  horometro NUMERIC,
  descripcion TEXT NOT NULL,
  costo NUMERIC NOT NULL DEFAULT 0 CHECK (costo >= 0),
  proveedor TEXT,
  responsable TEXT,
  registrado_por TEXT,
  empresa TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS maquinaria_fallas_empresa_equipo_fecha_idx ON public.maquinaria_fallas(empresa, equipo_id, fecha DESC);
CREATE INDEX IF NOT EXISTS maquinaria_mantenciones_empresa_equipo_fecha_idx ON public.maquinaria_mantenciones(empresa, equipo_id, fecha DESC);

ALTER TABLE public.maquinaria_fallas ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.maquinaria_mantenciones ENABLE ROW LEVEL SECURITY;

