CREATE POLICY rrhh_proyecciones_select ON public.rrhh_proyecciones_dotacion FOR SELECT TO authenticated
USING (EXISTS (SELECT 1 FROM public.usuarios u WHERE u.auth_user_id = (SELECT auth.uid()) AND (u.empresa = rrhh_proyecciones_dotacion.empresa OR lower(u.empresa) = 'obraxis')));

