CREATE TABLE IF NOT EXISTS public.rrhh_proyecciones_dotacion (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  empresa TEXT NOT NULL,
  obra_nombre TEXT NOT NULL,
  cargo TEXT NOT NULL,
  fecha_inicio DATE NOT NULL,
  fecha_termino DATE NOT NULL,
  cantidad_requerida INTEGER NOT NULL DEFAULT 1 CHECK (cantidad_requerida > 0),
  costo_mensual_unitario NUMERIC NOT NULL DEFAULT 0 CHECK (costo_mensual_unitario >= 0),
  turno TEXT,
  estado TEXT NOT NULL DEFAULT 'Planificada' CHECK (estado IN ('Planificada','Confirmada','En contratación','Cubierta','Cancelada')),
  observaciones TEXT,
  creado_por TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (fecha_termino >= fecha_inicio)
);

CREATE INDEX IF NOT EXISTS rrhh_proyecciones_empresa_obra_periodo_idx
  ON public.rrhh_proyecciones_dotacion (empresa, obra_nombre, fecha_inicio, fecha_termino);

ALTER TABLE public.rrhh_proyecciones_dotacion ENABLE ROW LEVEL SECURITY;

