create table if not exists public.prevencion_matrices_riesgo (
  id uuid primary key default gen_random_uuid(),
  empresa text not null,
  obra_id integer references public.obras(id) on delete restrict,
  nombre text not null,
  codigo text not null,
  version text not null default '1',
  fecha_revision date not null default current_date,
  metodologia text not null default 'ISP Chile · Guía IPER v3 (2024)',
  estado text not null default 'Borrador' check (estado in ('Borrador', 'Vigente', 'En revisión', 'Obsoleta')),
  columnas jsonb not null default '[]'::jsonb check (jsonb_typeof(columnas) = 'array'),
  archivo_path text,
  archivo_nombre text,
  archivo_tipo text,
  creado_por text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (id, empresa),
  unique (empresa, codigo, version)
);

create table if not exists public.prevencion_matriz_riesgo_filas (
  id bigint generated by default as identity primary key,
  matriz_id uuid not null,
  empresa text not null,
  orden integer not null check (orden > 0),
  datos jsonb not null default '{}'::jsonb check (jsonb_typeof(datos) = 'object'),
  nivel_riesgo text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint prevencion_matriz_riesgo_filas_matriz_empresa_fk
    foreign key (matriz_id, empresa)
    references public.prevencion_matrices_riesgo(id, empresa)
    on delete cascade,
  unique (matriz_id, orden)
);

create index if not exists prevencion_matrices_riesgo_empresa_obra_idx
  on public.prevencion_matrices_riesgo (empresa, obra_id, estado);
create index if not exists prevencion_matriz_riesgo_filas_matriz_nivel_idx
  on public.prevencion_matriz_riesgo_filas (matriz_id, nivel_riesgo);

