drop policy if exists matrices_riesgo_storage_select on storage.objects;
create policy matrices_riesgo_storage_select on storage.objects
for select to authenticated
using (
  bucket_id = 'matrices-riesgo'
  and exists (
    select 1 from public.prevencion_matrices_riesgo matriz
    where matriz.archivo_path = name
      and (select private.obraxis_actor_can_access_company(matriz.empresa))
  )
);

drop policy if exists matrices_riesgo_storage_insert on storage.objects;
create policy matrices_riesgo_storage_insert on storage.objects
for insert to authenticated
with check (
  bucket_id = 'matrices-riesgo'
  and exists (
    select 1 from public.prevencion_matrices_riesgo matriz
    where matriz.id::text = (storage.foldername(name))[1]
      and (select private.obraxis_actor_can_access_company(matriz.empresa))
  )
);

