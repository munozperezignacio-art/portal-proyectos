create table if not exists public.auditoria_plataforma (
  id bigint generated by default as identity primary key,
  empresa text not null,
  obra_nombre text,
  modulo text not null,
  categoria text not null default 'operacion',
  accion text not null,
  descripcion text,
  entidad_tipo text,
  entidad_id text,
  actor_auth_user_id uuid,
  actor_usuario text,
  actor_nombre text,
  actor_rol text,
  actor_empresa text,
  origen text not null default 'plataforma',
  resultado text not null default 'exitoso',
  nivel text not null default 'informativo',
  metadatos jsonb not null default '{}'::jsonb,
  source_table text,
  source_id text,
  created_at timestamptz not null default now(),
  constraint auditoria_plataforma_resultado_check check (resultado in ('exitoso','fallido','pendiente','observado')),
  constraint auditoria_plataforma_nivel_check check (nivel in ('informativo','atencion','critico'))
);

