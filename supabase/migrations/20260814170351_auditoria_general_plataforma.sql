create or replace function private.usuario_puede_ver_auditoria(p_empresa text)
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1
    from public.usuarios u
    left join public.roles r on r.empresa = u.empresa and r.nombre = u.rol and coalesce(r.archivado, false) = false
    where u.auth_user_id = (select auth.uid())
      and (
        (u.empresa = 'Obraxis' and lower(coalesce(u.rol_base, u.rol, '')) in ('superusuario','superadmin'))
        or (
          u.empresa = p_empresa
          and (
            coalesce((u.permisos ->> 'admin.auditoria.ver')::boolean, false)
            or coalesce((r.permisos ->> 'admin.auditoria.ver')::boolean, false)
            or lower(coalesce(u.rol_base, u.rol, '')) in ('superusuario','superadmin','administrador','admin','gerencia')
          )
        )
      )
  );
$$;
revoke all on function private.usuario_puede_ver_auditoria(text) from public, anon, authenticated;
grant usage on schema private to authenticated;
grant execute on function private.usuario_puede_ver_auditoria(text) to authenticated;

drop policy if exists auditoria_select_autorizada on public.auditoria_plataforma;
create policy auditoria_select_autorizada on public.auditoria_plataforma
  for select to authenticated
  using ((select private.usuario_puede_ver_auditoria(empresa)));

create or replace function private.registrar_auditoria_cambio()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  payload jsonb := case when tg_op = 'DELETE' then to_jsonb(old) else to_jsonb(new) end;
  previous_payload jsonb := case when tg_op = 'UPDATE' then to_jsonb(old) else '{}'::jsonb end;
  v_empresa text;
  v_obra text;
  v_actor record;
  v_id text;
  v_modulo text := coalesce(tg_argv[0], tg_table_name);
  v_categoria text := coalesce(tg_argv[1], 'operacion');
  v_action text;
  v_changed text[];
begin
  v_empresa := coalesce(payload->>'empresa', payload->>'empresa_mandante', payload->>'empresa_contratista', payload->>'actor_empresa');
  if v_empresa is null or btrim(v_empresa) = '' then
    if tg_op = 'DELETE' then return old; else return new; end if;
  end if;
  v_obra := coalesce(payload->>'obra_nombre', payload->>'obra', payload->>'proyecto_nombre');
  v_id := coalesce(payload->>'id', payload->>'codigo', payload->>'folio');
  v_action := case tg_op when 'INSERT' then 'creado' when 'UPDATE' then 'actualizado' else 'eliminado' end;

  select u.usuario, u.nombre, coalesce(u.rol_base, u.rol) as rol, u.empresa
    into v_actor
    from public.usuarios u where u.auth_user_id = (select auth.uid()) limit 1;

  if tg_op = 'UPDATE' then
    select array_agg(k order by k) into v_changed
    from jsonb_object_keys(payload) k
    where payload->k is distinct from previous_payload->k
      and k not in ('updated_at','contrasena','token','clave','api_key','respuesta','pregunta','contenido','archivo_base64','logo_base64');
  end if;

  insert into public.auditoria_plataforma (
    empresa, obra_nombre, modulo, categoria, accion, descripcion,
    entidad_tipo, entidad_id, actor_auth_user_id, actor_usuario,
    actor_nombre, actor_rol, actor_empresa, origen, resultado, nivel,
    metadatos, source_table, source_id, created_at
  ) values (
    v_empresa, v_obra, v_modulo, v_categoria, v_action,
    initcap(replace(tg_table_name, '_', ' ')) || ' ' || v_action,
    tg_table_name, v_id, (select auth.uid()), v_actor.usuario,
    coalesce(v_actor.nombre, payload->>'actor_nombre', payload->>'actor'),
    v_actor.rol, coalesce(v_actor.empresa, payload->>'actor_empresa', v_empresa),
    case when (select auth.uid()) is null then 'automatizacion' else 'plataforma' end,
    'exitoso', 'informativo',
    jsonb_strip_nulls(jsonb_build_object('campos_modificados', to_jsonb(v_changed), 'estado', coalesce(payload->>'estado', payload->>'estado_destino'))),
    tg_table_name, case when v_id is null then null else tg_op || ':' || v_id || ':' || coalesce(payload->>'updated_at', payload->>'created_at', clock_timestamp()::text) end,
    coalesce((payload->>'created_at')::timestamptz, now())
  ) on conflict do nothing;
  if tg_op = 'DELETE' then return old; else return new; end if;
exception when others then
  -- La auditorÃ­a nunca debe bloquear la operaciÃ³n de negocio.
  if tg_op = 'DELETE' then return old; else return new; end if;
end;
$$;
revoke all on function private.registrar_auditoria_cambio() from public, anon, authenticated;

do $$
declare r record;
begin
  for r in
    select * from (values
      ('obras','obras','obra'), ('avances_produccion_partidas','avances','obra'),
      ('estados_pago_obra','estados_pago','obra'), ('libro_obra_digital','libro_obra','obra'),
      ('calidad_pac','calidad','obra'), ('calidad_rdi','calidad','obra'),
      ('calidad_no_conformidades','calidad','obra'), ('calidad_recepciones_partidas','calidad','obra'),
      ('prevencion_respuestas','prevencion','obra'), ('prevencion_cumplimiento_registros','prevencion','obra'),
      ('inventario_maquinaria','maquinaria','operacion'), ('maquinaria_mantenciones','maquinaria','operacion'),
      ('maquinaria_fallas','maquinaria','operacion'), ('maquinaria_reservas','maquinaria','operacion'),
      ('maestro_personal','rrhh','operacion'), ('asistencia_personal','rrhh','obra'),
      ('bodega_movimientos','bodega','operacion'), ('gastos_rendiciones','gastos','operacion'),
      ('dte_documentos_operacion','facturacion','tributario'), ('dte_eventos','facturacion','tributario'),
      ('clientes_portal_eventos','clientes','portal'), ('contratos_colaborativos_eventos','colaboracion','contrato'),
      ('mandante_eventos','mandante','contrato'), ('subcontrato_avances','subcontratos','obra'),
      ('subcontrato_asistencia','subcontratos','obra'), ('subcontrato_estados_pago','subcontratos','obra'),
      ('ia_consumos','ia','inteligencia_artificial'), ('copiloto_obra_consultas','ox','inteligencia_artificial'),
